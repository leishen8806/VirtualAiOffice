import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import { createHash } from 'node:crypto'
import { gunzipSync } from 'node:zlib'

const root = new URL('../../', import.meta.url)
const manifest = JSON.parse(fs.readFileSync(new URL('../assets/compact/MANIFEST.json', import.meta.url)))
const hash = bytes => createHash('sha256').update(bytes).digest('hex')

test('compact outputs bind every retained source and generated byte sequence', () => {
  assert.equal(manifest.originalFilesRetained, true)
  assert.equal(new Set(manifest.files.map(x => x.file)).size, manifest.files.length)
  for (const row of manifest.files) {
    const bytes = fs.readFileSync(new URL(row.file, root))
    assert.equal(bytes.length, row.bytes, row.file); assert.equal(hash(bytes), row.sha256, row.file)
    assert.equal(hash(fs.readFileSync(new URL(row.source, root))), row.sourceSha256, row.source)
  }
})

test('all source avatar directories and 56 Rocketbox clips have validated compact replacements', () => {
  const avatars = fs.readdirSync(new URL('../assets/models/people/', import.meta.url), { withFileTypes: true }).filter(d => d.isDirectory() && d.name !== 'anim').map(d => d.name).sort()
  const models = manifest.files.filter(x => x.kind === 'model')
  assert.deepEqual(models.map(x => x.file.split('/').at(-1).replace('.glb.gz', '')).sort(), avatars)
  for (const row of models) {
    const bytes = gunzipSync(fs.readFileSync(new URL(row.file, root)))
    assert.equal(bytes.toString('ascii', 0, 4), 'glTF'); assert.equal(bytes.readUInt32LE(4), 2)
    assert.equal(row.validation.bones, 81); assert.ok(row.validation.vertices > 1000)
    assert.ok(row.validation.vertexErrorSourceUnits < .001)
  }
  const clips = manifest.files.filter(x => x.kind === 'animation' && x.source.endsWith('.fbx'))
  assert.equal(clips.length, 56)
  for (const row of clips) { assert.ok(row.bytes < 500000, row.file); assert.ok(row.validation.samples > 0); assert.ok(row.validation.maxError <= 2e-5, row.file) }
  assert.equal(manifest.files.find(x => x.source.endsWith('UAL1_Standard.glb')).validation.clips, 5)
})

test('both texture tiers are complete, with no source or runtime Three upgrade', () => {
  const textures = manifest.files.filter(x => x.kind === 'texture')
  const sources = new Set(textures.map(x => x.source))
  for (const source of sources) {
    const rows = textures.filter(x => x.source === source)
    assert.equal(rows.length, 2)
    for (const size of [512, 1024]) {
      const row = rows.find(x => x.file.includes(`/${size}/`))
      assert.ok(row); assert.ok(row.dimensions.every(n => n <= size && n > 0)); assert.match(row.file, /\.webp$/)
    }
  }
  const vendor = JSON.parse(fs.readFileSync(new URL('../../scripts/perf-load-2/vendor/SOURCES.json', import.meta.url)))
  assert.equal(vendor.revision, 'r185'); assert.equal(vendor.runtimeUpgrade, false)
  assert.equal(hash(fs.readFileSync(new URL('../../scripts/perf-load-2/vendor/exporters/GLTFExporter.js', import.meta.url))), vendor.files[0].sha256)
})

test('cartoon GLB packaging preserves every JSON field and geometry byte', () => {
  const rows = manifest.files.filter(x => x.kind === 'cartoon-model')
  assert.equal(rows.length, 8)
  for (const row of rows) {
    const original = JSON.parse(fs.readFileSync(new URL(row.source, root)))
    const sourceBuffer = fs.readFileSync(new URL(row.sourceBuffer, root))
    assert.equal(hash(sourceBuffer), row.sourceBufferSha256)
    const glb = gunzipSync(fs.readFileSync(new URL(row.file, root))), length = glb.readUInt32LE(12)
    const decoded = JSON.parse(glb.subarray(20, 20 + length).toString())
    delete original.buffers[0].uri
    assert.deepEqual(decoded, original)
    assert.deepEqual(glb.subarray(28 + length, 28 + length + sourceBuffer.length), sourceBuffer)
  }
})
